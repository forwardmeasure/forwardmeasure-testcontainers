package com.forwardmeasure.testcontainers.cassandra;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.TimeUnit;

/**
 * Fresh disposable server/client certificates generated by this JDK's keytool. No checked-in
 * private keys, expired certificates, global truststore edits or external certificate tools.
 * Creating material does not start Docker; callers retain it until their containers have stopped.
 */
public final class CassandraTlsMaterial implements AutoCloseable {
  private static final String PASSWORD = "disposable-fixture-only";
  private final Path directory;
  private boolean closed;
  private final CassandraTlsConfiguration.Store server;
  private final CassandraTlsConfiguration.Store client;
  private final CassandraTlsConfiguration.Store serverTrust;
  private final CassandraTlsConfiguration.Store clientTrust;

  private CassandraTlsMaterial(Path directory) {
    this.directory = directory;
    generate("server", "localhost", "SAN=dns:localhost,ip:127.0.0.1");
    generate("client", "cassandra-client", null);
    export("server");
    export("client");
    trust("server-trust", "client");
    trust("client-trust", "server");
    server = store("server");
    client = store("client");
    serverTrust = store("server-trust");
    clientTrust = store("client-trust");
  }

  public static CassandraTlsMaterial create() {
    Path directory;
    try {
      directory = Files.createTempDirectory("forwardmeasure-cassandra-tls-");
    } catch (IOException failure) {
      throw new UncheckedIOException(failure);
    }
    try {
      return new CassandraTlsMaterial(directory);
    } catch (RuntimeException failure) {
      delete(directory);
      throw failure;
    }
  }

  public CassandraTlsConfiguration configuration(boolean mutualTls) {
    return new CassandraTlsConfiguration(
        server,
        serverTrust,
        clientTrust,
        mutualTls ? Optional.of(client) : Optional.empty(),
        mutualTls,
        true);
  }

  private CassandraTlsConfiguration.Store store(String name) {
    return new CassandraTlsConfiguration.Store(directory.resolve(name + ".jks"), PASSWORD);
  }

  private void generate(String name, String commonName, String extension) {
    var arguments =
        new ArrayList<>(
            List.of(
                "-genkeypair",
                "-alias",
                name,
                "-keyalg",
                "RSA",
                "-keysize",
                "2048",
                "-validity",
                "30",
                "-dname",
                "CN=" + commonName,
                "-storetype",
                "JKS",
                "-keystore",
                directory.resolve(name + ".jks").toString(),
                "-storepass",
                PASSWORD,
                "-keypass",
                PASSWORD,
                "-noprompt"));
    if (extension != null) {
      arguments.addAll(List.of("-ext", extension));
    }
    keytool(arguments);
  }

  private void export(String name) {
    keytool(
        List.of(
            "-exportcert",
            "-alias",
            name,
            "-keystore",
            directory.resolve(name + ".jks").toString(),
            "-storepass",
            PASSWORD,
            "-file",
            directory.resolve(name + ".cer").toString()));
  }

  private void trust(String name, String peer) {
    keytool(
        List.of(
            "-importcert",
            "-alias",
            peer,
            "-storetype",
            "JKS",
            "-keystore",
            directory.resolve(name + ".jks").toString(),
            "-storepass",
            PASSWORD,
            "-file",
            directory.resolve(peer + ".cer").toString(),
            "-noprompt"));
  }

  private static void keytool(List<String> arguments) {
    var command = new ArrayList<String>();
    command.add(Path.of(System.getProperty("java.home"), "bin", "keytool").toString());
    command.addAll(arguments);
    try {
      // Fixture passwords and keytool command lines are deliberately excluded from failures.
      Process process =
          new ProcessBuilder(command)
              .redirectError(ProcessBuilder.Redirect.DISCARD)
              .redirectOutput(ProcessBuilder.Redirect.DISCARD)
              .start();
      try {
        if (!process.waitFor(Duration.ofSeconds(30).toMillis(), TimeUnit.MILLISECONDS)) {
          throw new IllegalStateException("JDK keytool did not complete within 30 seconds");
        }
        if (process.exitValue() != 0) {
          throw new IllegalStateException("JDK keytool could not create fixture TLS material");
        }
      } finally {
        if (process.isAlive()) {
          process.destroyForcibly();
        }
      }
    } catch (IOException failure) {
      throw new UncheckedIOException(failure);
    } catch (InterruptedException interrupted) {
      Thread.currentThread().interrupt();
      throw new IllegalStateException("Interrupted creating fixture TLS material", interrupted);
    }
  }

  private static void delete(Path directory) {
    try (var paths = Files.walk(directory)) {
      for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) {
        Files.deleteIfExists(path);
      }
    } catch (IOException failure) {
      throw new UncheckedIOException(failure);
    }
  }

  @Override
  public void close() {
    if (!closed) {
      closed = true;
      delete(directory);
    }
  }
}
